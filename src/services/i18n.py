_CURRENT_LANG = "zh-CN"


def get_system_default_language() -> str:
    """自动检测操作系统显示语言：中文系统返回 'zh-CN'，其他系统返回 'en-US'"""
    import sys
    import ctypes
    import locale
    try:
        if sys.platform == "win32":
            windll = getattr(ctypes, "windll", None)
            if windll and hasattr(windll, "kernel32") and hasattr(windll.kernel32, "GetUserDefaultUILanguage"):
                lang_id = windll.kernel32.GetUserDefaultUILanguage()
                # 0x0804 (zh-CN), 0x0404 (zh-TW), 0x0c04 (zh-HK)
                if (lang_id & 0xFF) == 0x04:
                    return "zh-CN"
                return "en-US"
        loc = locale.getdefaultlocale()[0]
        if loc and loc.lower().startswith("zh"):
            return "zh-CN"
        return "en-US"
    except Exception:
        pass
    return "zh-CN"


def set_language(lang: str) -> None:
    global _CURRENT_LANG
    if lang in TRANSLATIONS:
        _CURRENT_LANG = lang


def get_language() -> str:
    return _CURRENT_LANG


def t(key: str, default: str = "") -> str:
    """获取指定键的多语言文本"""
    dict_lang = TRANSLATIONS.get(_CURRENT_LANG, TRANSLATIONS["zh-CN"])
    return dict_lang.get(key, default or key)
